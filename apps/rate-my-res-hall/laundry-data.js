export function summarizeHall(hall) {
  const washers = hall.rooms.length ? hall.rooms.reduce((sum, room) => sum + room.washers, 0) : null;
  const dryers = hall.rooms.length ? hall.rooms.reduce((sum, room) => sum + room.dryers, 0) : null;
  return { ...hall, washers, dryers, residentsPerWasher: Number.isFinite(hall.capacity) && washers > 0 ? hall.capacity / washers : null };
}
export function rankedHalls(halls = laundryHalls) {
  return halls.map(summarizeHall).sort((a, b) => (a.residentsPerWasher ?? Infinity) - (b.residentsPerWasher ?? Infinity) || a.name.localeCompare(b.name));
}
